"""Generates and manages transparent CLI shims for pip/pip3/npm/cargo in ~/.local/bin.

The shim first consults the Data Guardian approval gate; if the gate cannot run
at all (e.g. the project was moved), read-only commands still execute and only
download-style commands are refused, so the tool never becomes unusable silently.
"""

from __future__ import annotations

import os
import stat
from pathlib import Path
from typing import List

SUPPORTED_TOOLS = ["pip", "pip3", "npm", "cargo"]

PROJECT_MARKER = "project_dir"

SHIM_TEMPLATE = """#!/usr/bin/env bash
# ==============================================================================
# Linux Data Guardian — CLI Shim for {tool}
# Auto-generated by 'data-guardian install-shims'. Do not edit manually.
# ==============================================================================

DG_MARKER="${{XDG_CONFIG_HOME:-$HOME/.config}}/linux-data-guardian/project_dir"
PROJECT_DIR="{project_dir}"
if [ -r "$DG_MARKER" ]; then
    PROJECT_DIR=$(cat "$DG_MARKER")
fi

if [ -d "$PROJECT_DIR/src/data_guardian" ]; then
    PYTHONPATH="$PROJECT_DIR:${{PYTHONPATH:-}}" /usr/bin/python3 \\
        -m src.data_guardian.approvals.gate --tool "{tool}" "$@"
    GATE_EXIT=$?
    if [ $GATE_EXIT -ne 0 ]; then
        exit $GATE_EXIT
    fi
else
    # Gate unavailable: refuse clearly-downloading invocations, allow read-only.
    case " $* " in
        *" install "*|*" update "*|*" upgrade "*|*" download "*|*" add "*|*" upgrade "*|*" fetch "*)
            echo "[!] Linux Data Guardian: approval gate unavailable (project dir '$PROJECT_DIR')." >&2
            echo "    Refusing a download command on a metered connection. Fix with: data-guardian install-shims" >&2
            exit 1
            ;;
    esac
fi

# Locate the real binary, skipping this shim (self) by path identity.
THIS_SCRIPT=$(realpath "$0" 2>/dev/null || echo "$0")
SELF_DIR=$(dirname "$THIS_SCRIPT")
REAL_BIN=""
OLD_IFS=$IFS
IFS=:
for dir in $PATH; do
    candidate="$dir/{tool}"
    [ -x "$candidate" ] || continue
    [ -d "$candidate" ] && continue
    candidate_real=$(realpath "$candidate" 2>/dev/null || echo "$candidate")
    if [ "$candidate_real" != "$THIS_SCRIPT" ] && [ "$(dirname "$candidate_real")" != "$SELF_DIR" ]; then
        REAL_BIN="$candidate"
        break
    fi
done
IFS=$OLD_IFS

if [ -n "$REAL_BIN" ]; then
    exec "$REAL_BIN" "$@"
fi

# Nothing to delegate to (e.g. pip3 not installed): run the plain name and let
# the shell report the usual 'command not found'.
exec "{tool}" "$@"
"""


def project_dir() -> Path:
    return Path(__file__).resolve().parent.parent.parent.parent


def default_config_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME")
    root = Path(base) if base else Path.home() / ".config"
    return root / "linux-data-guardian"


def write_project_marker(dest_config_dir: Path | None = None) -> Path:
    """Record where the project lives so shims survive being moved/renamed."""
    config_dir = dest_config_dir or default_config_dir()
    config_dir.mkdir(parents=True, exist_ok=True)
    marker = config_dir / PROJECT_MARKER
    marker.write_text(str(project_dir()) + "\n", encoding="utf-8")
    try:
        marker.chmod(0o600)
    except OSError:
        pass
    return marker


def install_shims(
    target_dir: Path | None = None, config_dir: Path | None = None
) -> List[Path]:
    """Install shims into ``target_dir`` (default ``~/.local/bin``)."""
    dest = target_dir or (Path.home() / ".local" / "bin")
    dest.mkdir(parents=True, exist_ok=True)
    write_project_marker(config_dir)

    installed: List[Path] = []
    for tool in SUPPORTED_TOOLS:
        shim_path = dest / tool
        shim_path.write_text(
            SHIM_TEMPLATE.format(tool=tool, project_dir=str(project_dir())),
            encoding="utf-8",
        )
        shim_path.chmod(shim_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        installed.append(shim_path)
    return installed


def remove_shims(
    target_dir: Path | None = None, config_dir: Path | None = None
) -> List[Path]:
    """Remove our shims; leave anything else in the directory untouched."""
    dest = target_dir or (Path.home() / ".local" / "bin")
    removed: List[Path] = []
    for tool in SUPPORTED_TOOLS:
        shim_path = dest / tool
        if not shim_path.exists():
            continue
        try:
            content = shim_path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        if "Linux Data Guardian" in content:
            try:
                shim_path.unlink()
                removed.append(shim_path)
            except OSError as exc:
                print(f"[!] Warning removing shim {shim_path}: {exc}")
    try:
        ((config_dir or default_config_dir()) / PROJECT_MARKER).unlink(missing_ok=True)
    except OSError:
        pass
    return removed
